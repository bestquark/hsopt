"""Matrix-based Hamiltonian implementations."""

from __future__ import annotations
from typing import Any, Dict, Sequence, Optional, List

import cupynumeric as np

from trovolut.qm.hamiltonians._hamiltonian import Hamiltonian, HamiltonianEnsemble


class MatrixHamiltonian(Hamiltonian):
    r"""Deterministic Hamiltonian defined by explicit dense matrices.

    Args:
        H_total (np.ndarray): Hermitian matrix for the full Hamiltonian.
        term_list (Sequence[Dict[str, np.ndarray]] | None): Optional additive
            decomposition ``{"coef": c, "matrix": H_i}`` such that
            $\sum_i c H_i = H_{\text{total}}$. If omitted, a single identity term is
            inferred.
    """

    def __init__(
        self,
        H_total: np.ndarray,
        term_list: Optional[Sequence[Dict[str, np.ndarray]]] = None,
    ):
        H_total = np.array(H_total, dtype=complex)
        if H_total.shape[0] != H_total.shape[1]:
            raise ValueError("H_total must be square")
        if not np.allclose(H_total, H_total.conj().T):
            raise ValueError("H_total must be Hermitian")

        self._H = H_total
        self._dim = H_total.shape[0]

        # Validate / set decomposition
        if term_list is not None:
            recon = np.zeros_like(self._H)
            validated_terms = []
            for t in term_list:
                coef = complex(t["coef"])
                block = np.array(t["matrix"], dtype=complex)
                if block.shape != (self._dim, self._dim):
                    raise ValueError("term matrix has wrong shape")
                if not np.allclose(block, block.conj().T):
                    raise ValueError("term matrix must be Hermitian")
                validated_terms.append({"coef": coef, "matrix": block})
                recon += coef * block
            if not np.allclose(recon, self._H):
                raise ValueError("term_list does not sum back to H_total")
            self._term_list = validated_terms
        else:
            self._term_list = [{"coef": 1.0, "matrix": self._H}]

    @property
    def hilbert_dim(self) -> int:
        """int: Hilbert-space dimension of ``H_total``."""
        return self._dim

    def to_matrix(self) -> np.ndarray:
        """np.ndarray: Dense Hermitian matrix of the Hamiltonian."""
        return self._H

    def terms(self) -> Sequence[Dict[str, np.ndarray]]:
        """Return a copy of the stored additive decomposition.

        Returns:
            Sequence[Dict[str, np.ndarray]]:
                List of ``{"coef", "matrix"}`` entries with matrices copied to avoid aliasing.
        """
        return [
            {"coef": t["coef"], "matrix": np.array(t["matrix"], copy=True)} for t in self._term_list
        ]

    def decompose(self) -> Dict[str, Any]:
        """Return metadata describing the deterministic matrix Hamiltonian.

        Returns:
            Dict[str, Any]: Lightweight description with dimension, number of terms, and raw coefficients.
        """
        return {
            "type": "matrix",
            "dim": self._dim,
            "n_terms": len(self._term_list),
            "coefficients": [complex(t["coef"]) for t in self._term_list],
        }


class WeightedRandomHamiltonian(HamiltonianEnsemble):
    """Ensemble of random Hermitian matrices combined with random coefficients.

    Each term ``H_i`` is generated by symmetrizing a random complex Gaussian
    matrix and the coefficients are drawn from a user-specified distribution.

    Args:
        n (int): Hilbert-space dimension.
        m (int): Number of Hermitian terms per sample.
        coef_dist (dict | None): Distribution specification. Supported formats::

            {"type": "discrete", "values": [...], "probs": [...]}
            {"type": "uniform", "low": float, "high": float}
            {"type": "normal", "mean": float, "std": float}

            Defaults to a two-scale discrete distribution ``{10.0, 0.01}``.
    """

    def __init__(
        self,
        n: int = 100,
        m: int = 5,
        coef_dist: Optional[Dict[str, Any]] = None,
    ):
        self.n = int(n)
        self.m = int(m)
        self.coef_dist = coef_dist or {
            "type": "discrete",
            "values": [10.0, 0.01],
            "probs": [0.5, 0.5],
        }

    @property
    def hilbert_dim(self) -> int:
        """int: Hilbert-space dimension shared by all draws."""
        return self.n

    def _draw_coefs(self, rng: np.random.Generator) -> np.ndarray:
        """Draw random coefficients according to ``coef_dist``.

        Args:
            rng (np.random.Generator): Source of randomness.

        Returns:
            np.ndarray: Array of ``m`` coefficients.

        Raises:
            ValueError: If the distribution type is unknown.
        """
        d = self.coef_dist
        t = d["type"]

        if t == "discrete":
            vals = np.array(d["values"], dtype=float)
            probs = np.array(d.get("probs", np.ones_like(vals) / len(vals)))
            return rng.choice(vals, size=self.m, p=probs)

        elif t == "uniform":
            low = d.get("low", -1.0)
            high = d.get("high", 1.0)
            return rng.uniform(low, high, size=self.m)

        elif t == "normal":
            mean = d.get("mean", 0.0)
            std = d.get("std", 1.0)
            return rng.normal(mean, std, size=self.m)

        else:
            raise ValueError(f"Unknown coef_dist type {t}")

    def _draw_terms(self, rng: np.random.Generator) -> List[Dict[str, np.ndarray]]:
        """Generate random Hermitian blocks for the ensemble sample.

        Args:
            rng (np.random.Generator): Source of randomness.

        Returns:
            List[Dict[str, np.ndarray]]: Raw term list with ``coef`` and ``matrix`` entries.
        """
        n = self.n
        coefs = self._draw_coefs(rng)
        terms = []
        for coef_i in coefs:
            A = rng.standard_normal((n, n)) + 1j * rng.standard_normal((n, n))
            H_i = (A + A.conj().T) / 2.0
            terms.append({"coef": coef_i, "matrix": H_i})
        return terms

    def sample(self, rng: Optional[np.random.Generator] = None) -> MatrixHamiltonian:
        """Draw one deterministic Hamiltonian from the ensemble.

        Args:
            rng (np.random.Generator | None): Optional RNG.

        Returns:
            MatrixHamiltonian: Deterministic Hamiltonian representing the draw.
        """
        rng = rng or np.random.default_rng()
        terms = self._draw_terms(rng)
        H_total = np.sum([t["coef"] * t["matrix"] for t in terms], axis=0)
        return MatrixHamiltonian(H_total, term_list=terms)

    def decompose(self) -> Dict[str, Any]:
        """Describe the ensemble in a JSON-serializable way.

        Returns:
            Dict[str, Any]: Metadata including dimension, number of terms, and coefficient distribution descriptor.
        """
        return {
            "type": "weighted_random_ensemble",
            "dim": self.n,
            "m_terms": self.m,
            "coef_dist": self.coef_dist,
            "distribution": "complex Gaussian Hermitian symmetrized",
        }
