def run_with_legate(program: str, H_terms, psi0, t) -> Tuple[np.ndarray, Dict[str, Any], str]:
    """Run candidate under Legate with profiling."""
    WORKDIR.mkdir(parents=True, exist_ok=True)
    
    # Prepare input pickle
    in_pkl = WORKDIR / ".legate_in.pkl"
    with open(in_pkl, "wb") as f:
        pickle.dump((H_terms, psi0, float(t)), f)
    
    # Clean old profiles
    for p in WORKDIR.glob("legate_*.prof"):
        shutil.rmtree(p, ignore_errors=True)
    
    # Run with Legate
    cmd = [
        "uv", "run", "legate", "--profile",
        "--gpus", str(GPUS),
        "--cpus", str(CPUS),
        "--fbmem", str(FBMEM_MB),
        program,
        "--pickle", str(in_pkl),
    ]
    
    proc = subprocess.run(cmd, cwd=str(WORKDIR), capture_output=True)
    
    if proc.returncode != 0:
        raise RuntimeError(f"Legate failed: {{proc.stderr.decode()[-2000:]}}")
    
    # Parse output
    try:
        psi_final, meta = pickle.loads(proc.stdout)
    except Exception:
        bio = io.BytesIO(proc.stdout)
        obj = None
        up = pickle.Unpickler(bio)
        try:
            while True:
                obj = up.load()
        except Exception:
            pass
        if not isinstance(obj, tuple) or len(obj) != 2:
            raise RuntimeError("Could not parse output")
        psi_final, meta = obj
    
    # Find profile directory
    prof_dirs = sorted(WORKDIR.glob("legate_*.prof"), key=lambda p: p.stat().st_mtime, reverse=True)
    latest_prof = str(prof_dirs[0]) if prof_dirs else ""
    
    return psi_final, (meta or {{}}), latest_prof


