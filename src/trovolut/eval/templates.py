def read_legate_profile(db_path: Path) -> Dict[str, Any]:
    """Read GPU metrics from a DuckDB profile database."""
    if not HAS_DUCKDB:
        return {{"gpu_seconds": 0.0, "makespan_seconds": 0.0, "avg_concurrency": 0.0,
                "peak_fb_mb": 0.0, "avg_fb_mb": 0.0}}
    
    con = duckdb.connect(str(db_path))
    
    # GPU time query
    time_q = r"""
    WITH gpu_items AS (
      SELECT e.long_name AS gpu, i.running.duration AS dur_us
      FROM items i JOIN entries e USING(entry_slug)
      WHERE i.running IS NOT NULL AND e.long_name ILIKE '%GPU% Device'
    ),
    per_gpu AS (
      SELECT gpu, SUM(dur_us) AS run_us FROM gpu_items GROUP BY gpu
    )
    SELECT COALESCE(SUM(run_us), 0) AS total_us FROM per_gpu;
    """
    
    makespan_q = r"""
    WITH gpu_items AS (
      SELECT i.running.start AS start_us, i.running.stop AS stop_us
      FROM items i JOIN entries e USING(entry_slug)
      WHERE i.running IS NOT NULL AND e.long_name ILIKE '%GPU% Device'
    )
    SELECT COALESCE(MAX(stop_us) - MIN(start_us), 0) AS makespan_us FROM gpu_items;
    """
    
    mem_q = r"""
    WITH fb_instances AS (
      SELECT i.size,
        CAST(REGEXP_EXTRACT(i.size, '([0-9.]+)') AS DOUBLE) AS v,
        CASE
          WHEN i.size ILIKE '%GiB%' THEN 1024.0*1024.0*1024.0
          WHEN i.size ILIKE '%MiB%' THEN 1024.0*1024.0
          WHEN i.size ILIKE '%KiB%' THEN 1024.0
          ELSE 1.0
        END AS mult
      FROM items i JOIN entries e USING(entry_slug)
      WHERE i.lifetime IS NOT NULL AND e.long_name ILIKE '%Framebuffer%'
    )
    SELECT COALESCE(MAX(v * mult), 0) AS peak_bytes FROM fb_instances WHERE v IS NOT NULL;
    """
    
    try:
        gpu_us = con.sql(time_q).fetchone()[0] or 0
        makespan_us = con.sql(makespan_q).fetchone()[0] or 0
        peak_bytes = con.sql(mem_q).fetchone()[0] or 0
    except Exception:
        gpu_us, makespan_us, peak_bytes = 0, 0, 0
    
    gpu_seconds = gpu_us / 1e6
    makespan_seconds = makespan_us / 1e6
    avg_concurrency = (gpu_seconds / makespan_seconds) if makespan_seconds > 0 else 0.0
    
    return {{
        "gpu_seconds": gpu_seconds,
        "makespan_seconds": makespan_seconds,
        "avg_concurrency": avg_concurrency,
        "peak_fb_mb": peak_bytes / (1024 * 1024),
        "avg_fb_mb": peak_bytes / (1024 * 1024) * 0.5,  # estimate
    }}


