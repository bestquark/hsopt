def load_module(path):
    """Load a Python module from file path."""
    spec = importlib.util.spec_from_file_location("candidate", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_with_timeout(func, args=(), kwargs=None, timeout_seconds=30):
    """Run a function with a timeout."""
    if kwargs is None:
        kwargs = {{}}
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
        future = executor.submit(func, *args, **kwargs)
        try:
            return future.result(timeout=timeout_seconds)
        except concurrent.futures.TimeoutError:
            raise TimeoutError(f"Timed out after {{timeout_seconds}} seconds")


def compute_metrics(program_path):
    """Run the candidate program and compute all metrics."""
    module = load_module(program_path)
    
    if not hasattr(module, RUN_FN_NAME):
        raise AttributeError(f"Module missing '{{RUN_FN_NAME}}' function")
    
    run_fn = getattr(module, RUN_FN_NAME)
    
    # Get Hamiltonian
    hams = {hamiltonian_fn_name}()
    if hasattr(hams, '__iter__') and not isinstance(hams, np.ndarray):
        hams = list(hams)
    
    # Remove identity term if present
    if len(hams) > 1:
        first = hams[0]
        if np.allclose(first, np.eye(first.shape[0]) * first[0, 0]):
            hams = hams[1:]
    
    H_full = sum(hams)
    U_exact = scipy.linalg.expm(-1j * H_full * TOTAL_TIME)
    dim = U_exact.shape[0]
    
    # Random initial states
    rng = np.random.default_rng(42)
    psi0_batch = rng.random((TRIALS, dim)) + 1j * rng.random((TRIALS, dim))
    psi0_batch = psi0_batch / np.linalg.norm(psi0_batch, axis=1)[:, np.newaxis]
    
    psi_exact_batch = psi0_batch @ U_exact.T
    
    # Run candidate
    start_time = time.perf_counter()
    psi_trotter_batch = np.array([
        run_fn(hams, TOTAL_TIME, psi0_batch[i])
        for i in range(TRIALS)
    ])
    elapsed_time = time.perf_counter() - start_time
    
    # Compute errors
    errors = np.linalg.norm(psi_trotter_batch - psi_exact_batch, axis=1)
    
    return {{
        "time_seconds": elapsed_time,
        "mean_error": float(np.mean(errors)),
        "std_error": float(np.std(errors)),
        "errors": errors.tolist(),
    }}


