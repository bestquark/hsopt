"""
Compare H2 product-formula precision policies with a simple QPE-style
ground-state phase readout.

The protocol uses the exact ground state as the QPE eigenstate input.  This
isolates the energy phase generated by the implemented product-formula unitary:
E is inferred from arg(<psi_0|U_pf|psi_0>)/t, unwrapped near the known reference
energy, and the Hamiltonian identity shift is added back.
"""

from __future__ import annotations

import argparse
import json
import math
import warnings
from pathlib import Path
from typing import Any

import numpy as np

import evaluate as ev


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_CASES = (
    ("initial_pf_iter_0000", SCRIPT_DIR / "h2/snapshots/iter_0000/simple_pf.py"),
    ("energy_valid_optimized_iter_0004", SCRIPT_DIR / "h2/snapshots/iter_0004/simple_pf.py"),
    ("final_t_optimized_iter_0100", SCRIPT_DIR / "h2/simple_pf.py"),
)


def energy_from_phase(
    phase: float,
    target_time: float,
    reference_energy: float,
    identity_shift: float,
) -> float:
    centered_reference_energy = float(reference_energy - identity_shift)
    centered_energy = ev.unwrap_energy_near_reference(
        phase,
        target_time,
        centered_reference_energy,
    )
    return float(centered_energy + identity_shift)


def round_phase_to_qpe_grid(phase: float, phase_bits: int) -> tuple[int, float]:
    if phase_bits < 1:
        raise ValueError("phase_bits must be positive")
    n_bins = 1 << phase_bits
    phase_fraction = (phase % (2.0 * math.pi)) / (2.0 * math.pi)
    phase_index = int(round(phase_fraction * n_bins)) % n_bins
    rounded_phase = (2.0 * math.pi * phase_index) / n_bins
    if rounded_phase > math.pi:
        rounded_phase -= 2.0 * math.pi
    return phase_index, float(rounded_phase)


def run_case(
    *,
    label: str,
    script_path: Path,
    problem: dict[str, Any],
    phase_bits: int | None,
) -> dict[str, Any]:
    module = ev.load_method_module(script_path)
    ground_problem = dict(problem)
    ground_problem["initial_state"] = np.array(problem["ground_state"], dtype=np.complex128, copy=True)

    quantized = module.run_product_formula(ground_problem, exact_angles=False)
    exact_angles = module.run_product_formula(ground_problem, exact_angles=True)

    ground_state = np.array(problem["ground_state"], dtype=np.complex128, copy=False)
    target_time = float(problem["target_time"])
    reference_energy = float(problem["ground_state_energy_hartree"])
    identity_shift = float(problem["identity_coefficient"])

    propagated = np.array(quantized["state"], dtype=np.complex128, copy=False)
    overlap = np.vdot(ground_state, propagated)
    phase = float(np.angle(overlap))
    energy_estimate = energy_from_phase(phase, target_time, reference_energy, identity_shift)

    exact_propagated = np.array(exact_angles["state"], dtype=np.complex128, copy=False)
    exact_overlap = np.vdot(ground_state, exact_propagated)
    exact_phase = float(np.angle(exact_overlap))
    exact_energy_estimate = energy_from_phase(exact_phase, target_time, reference_energy, identity_shift)

    qpe_grid: dict[str, Any] | None = None
    if phase_bits is not None:
        phase_index, rounded_phase = round_phase_to_qpe_grid(phase, phase_bits)
        qpe_energy = energy_from_phase(rounded_phase, target_time, reference_energy, identity_shift)
        qpe_grid = {
            "phase_bits": phase_bits,
            "phase_index": phase_index,
            "energy_estimate_hartree": qpe_energy,
            "energy_error_hartree": abs(qpe_energy - reference_energy),
        }

    return {
        "case": label,
        "script": str(script_path),
        "ground_state_energy_hartree": reference_energy,
        "target_time": target_time,
        "identity_coefficient": identity_shift,
        "continuous_phase_energy_estimate_hartree": energy_estimate,
        "continuous_phase_energy_error_hartree": abs(energy_estimate - reference_energy),
        "exact_angle_energy_estimate_hartree": exact_energy_estimate,
        "exact_angle_energy_error_hartree": abs(exact_energy_estimate - reference_energy),
        "phase_overlap_magnitude": float(abs(overlap)),
        "t_gate_count": int(quantized["t_gate_count"]),
        "unique_compilation_count": int(quantized["unique_compilation_count"]),
        "synthesis_epsilon_histogram": quantized["synthesis_epsilon_histogram"],
        "chemical_accuracy_hartree": float(problem["chemical_accuracy_hartree"]),
        "passes_chemical_accuracy": abs(energy_estimate - reference_energy) <= float(problem["chemical_accuracy_hartree"]),
        "qpe_grid": qpe_grid,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Run an H2 QPE-style energy comparison for PF precision policies.")
    parser.add_argument("--molecule", default="h2", help="Molecule problem cache to load.")
    parser.add_argument(
        "--phase-bits",
        type=int,
        default=20,
        help="Also report the nearest-grid energy from this many QPE phase bits. Use 0 to disable.",
    )
    parser.add_argument(
        "--case",
        action="append",
        metavar="LABEL=PATH",
        help="Override default cases. May be supplied more than once.",
    )
    args = parser.parse_args()

    if args.case:
        cases = []
        for raw_case in args.case:
            if "=" not in raw_case:
                raise SystemExit(f"case must be LABEL=PATH, got {raw_case!r}")
            label, raw_path = raw_case.split("=", 1)
            cases.append((label, Path(raw_path).expanduser().resolve()))
    else:
        cases = [(label, path.resolve()) for label, path in DEFAULT_CASES]

    phase_bits = None if args.phase_bits == 0 else args.phase_bits
    problem = ev.build_problem(args.molecule)

    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", category=RuntimeWarning)
        results = [
            run_case(label=label, script_path=path, problem=problem, phase_bits=phase_bits)
            for label, path in cases
        ]

    print(json.dumps(results, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
