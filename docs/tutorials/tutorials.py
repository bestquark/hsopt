from rdkit import Chem
from rdkit.Chem import AllChem
import cupynumeric as np

import legate_sparse as sparse



from trovolut.qm.hamiltonians import ElectronicHamiltonian

dmds_smiles = "CSSC"

# RDKit: SMILES -> mol
mol = Chem.MolFromSmiles(dmds_smiles)
mol = Chem.AddHs(mol)  # add hydrogens

# embed 3D coordinates
AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())
AllChem.UFFOptimizeMolecule(mol)

# extract XYZ as multiline string in standard XYZ format:
atoms = [atom.GetSymbol() for atom in mol.GetAtoms()]
conf = mol.GetConformer()

xyz_lines = []
xyz_lines.append(str(len(atoms)))
xyz_lines.append("dmds generated by RDKit")
for i, sym in enumerate(atoms):
    pos = conf.GetAtomPosition(i)
    xyz_lines.append(f"{sym} {pos.x:.8f} {pos.y:.8f} {pos.z:.8f}")

dmds_xyz = "\n".join(xyz_lines)

H_elec = ElectronicHamiltonian.from_xyz(
    xyz_source=dmds_xyz,
    basis="sto-3g",
    charge=0,
    spin_mult=1,
    use_gpu4pyscf=False,
    freeze_core=True,
    n_core_keep=3,
    n_virt_keep=3,
).to_qubits(mapping="jordan-wigner", sparse=True)

qmeta = H_elec.decompose()
hamcoeffs = H_elec.terms()

print("first 5 terms:")
for term in qmeta["terms"][:5]:
    print(term)

mats = [term['coef'] * term['matrix'] for term in hamcoeffs]

mats = [sparse.csr_matrix(mat) for mat in mats]

print(np.linalg.expm(-1j * mats[0] * 0.01) )